export const seedDailyStats: DailyStats[] = Array.from({ length: 30 }, (_, i) => {
  const day = 29 - i;
  const isWeekend = [1, 7, 8, 14, 15, 21, 22, 28].includes(day);
  const baseTxns = isWeekend ? 320 : 580;
  const variance = Math.floor(((i * 7 + 13) % 11) / 11 * 120) - 60;
  const txns = baseTxns + variance;
  const avgAmount = 2800 + ((i * 3 + 5) % 9) * 200;
  const highRiskPct = 0.03 + ((i * 11 + 2) % 7) * 0.005;
  const highRisk = Math.round(txns * highRiskPct);
  const blocked = Math.round(highRisk * 0.6);
  const chargebacks = Math.max(0, Math.round(txns * 0.005) - ((i * 3) % 3));
  const avgRisk = 28 + ((i * 7 + 3) % 15);

  return {
    date: daysAgo(day).split('T')[0],
    transactions: txns,
    totalVolume: txns * avgAmount,
    highRiskCount: highRisk,
    blockedCount: blocked,
    chargebackCount: chargebacks,
    avgRiskScore: avgRisk,
  };
});

